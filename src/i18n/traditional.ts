export function toTraditional(input: string): string {
  if (!input) return input;
  let out = input;
  for (const [simp, trad] of PHRASES) {
    if (out.includes(simp)) out = out.split(simp).join(trad);
  }
  out = Array.from(out)
    .map((ch) => CHARS[ch] ?? ch)
    .join('');
  return out;
}
